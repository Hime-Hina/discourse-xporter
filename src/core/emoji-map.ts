export function replaceEmoji(text: string): string {
  return transformOutsideCode(text, (prose) =>
    prose.replace(
      /:([a-zA-Z0-9_+\-]+):/g,
      (match, code: string) => EMOJI_MAP[code] ?? match,
    ),
  );
}
